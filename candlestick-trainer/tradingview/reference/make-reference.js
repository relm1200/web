// Runs the trainer's detector over real TradingView bars and writes the list of
// patterns the Pine indicator should mark. Usage: node tradingview/reference/make-reference.js <bars.json>
const fs = require('fs');
const path = require('path');
const L = require('../../js/patterns.js');
const S = require('../../js/structure.js');

const file = process.argv[2] || path.join(__dirname, 'OANDA_EURUSD_4h.json');
const d = JSON.parse(fs.readFileSync(file, 'utf8'));
const n = d.c.length;
for (const k of ['o', 'h', 'l', 't']) if (d[k].length !== n) throw new Error(`column ${k} has ${d[k].length} values, expected ${n}`);
const cs = d.c.map((c, i) => ({ o: d.o[i], h: d.h[i], l: d.l[i], c, t: d.t[i] }));
for (const k of cs) if (!(k.h >= Math.max(k.o, k.c) && k.l <= Math.min(k.o, k.c))) throw new Error('bad bar at ' + k.t);

// UTC times. TradingView shows the chart in the exchange or your chosen timezone.
const fmt = (t) => new Date(t * 1000).toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
const rows = [];
const counts = {};
// skip the last bar: it is still forming, and the indicator only marks closed candles
for (let i = 21; i < cs.length - 1; i++) {
  const all = L.detectAt(cs, i);
  for (const id of all) counts[id] = (counts[id] || 0) + 1;
  const ids = all.filter((id) => id !== 'spinning-top'); // off by default in the indicator
  if (!ids.length) continue;
  rows.push(`| ${fmt(cs[i].t)} | ${ids.map((id) => L.BY_ID[id].name).join(', ')} |`);
}
const { swings, trend } = S.analyse(cs.slice(0, -1));
const lastSwings = swings.filter((s) => s.label).slice(-6).map((s) => `${s.label} at ${fmt(cs[s.index].t)} (${s.kind === 'high' ? cs[s.index].h : cs[s.index].l})`);

const md = `# Reference marks: ${d.symbol} ${d.interval}

Generated by \`make-reference.js\` from ${n} bars (${fmt(cs[0].t)} to ${fmt(cs[n - 1].t)}), using
the trainer's detector (\`js/patterns.js\`) with the indicator's default settings. On that chart,
the indicator should mark exactly these candles. Spinning Top is off by default in the
indicator, so it is counted below but left out of the table. The first 21 bars are skipped
because the rules need history, and the last bar is skipped because it was still forming.

Times are candle **open** times in UTC. Data source: ${d.source}.

## Pattern count

${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([id, c]) => `- ${L.BY_ID[id].name}: ${c}`).join('\n')}

## Market structure at the end (swing strength 2)

Trend: **${S.TRENDS[trend.dir].name}**. Latest labelled swings:

${lastSwings.map((s) => `- ${s}`).join('\n')}

## Every marked candle

| Candle open (UTC) | Pattern(s) |
|---|---|
${rows.join('\n')}
`;
const out = path.join(path.dirname(file), path.basename(file, '.json') + '.md');
fs.writeFileSync(out, md);
console.log(`Wrote ${out}: ${rows.length} marked candles`);
console.log(counts);
