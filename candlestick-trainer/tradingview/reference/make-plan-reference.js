// Runs the Trend Pullback Plan reference (js/plan.js) over real bars and writes what the
// indicator should show with default settings. Usage: node make-plan-reference.js [bars.json] [pipSize]
const fs = require('fs');
const path = require('path');
const P = require('../../js/plan.js');

const file = process.argv[2] || path.join(__dirname, 'FX_USDJPY_5m.json');
const pipSize = Number(process.argv[3] || 0.01);
const d = JSON.parse(fs.readFileSync(file, 'utf8'));
const cs = d.c.map((c, i) => ({ o: d.o[i], h: d.h[i], l: d.l[i], c }));
const fmt = (t) => new Date(t * 1000).toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
const r = P.run(cs, { pipSize });
const start = 60; // warm-up: the slow average and Vortex need about 50 candles
const last = cs.length - 1; // still forming when fetched

let short = 0, long = 0, chop = 0;
const rows = [];
for (let i = start; i < last; i++) {
  const row = r.rows[i];
  if (row.dir < 0) short++;
  if (row.dir > 0) long++;
  if (row.chop) chop++;
  for (const [k, side] of [['sell', -1], ['buy', 1]]) {
    const x = row[k];
    if (!x || !x.name || row.dir !== side) continue;
    const p = x.plan;
    const why = x.signal ? '**signal**' : [
      row.chop ? 'choppy' : null,
      x.zone ? null : 'not in the pullback zone',
      p.stopOk ? null : 'stop past the slow average',
      Number.isNaN(p.t1) ? 'no target level' : p.rrOk ? null : `first target only ${p.rr1.toFixed(2)}R`,
    ].filter(Boolean).join('; ');
    rows.push(`| ${fmt(d.t[i])} | ${k === 'sell' ? 'Sell' : 'Buy'}: ${x.name} | ${cs[i].c} | ${p.stop.toFixed(3)} | ${Number.isNaN(p.t1) ? '-' : p.t1} | ${why} |`);
  }
}
const n = last - start;
const md = `# Reference: Trend Pullback Plan on ${d.symbol} ${d.interval}

${n} closed candles from ${fmt(d.t[start])} to ${fmt(d.t[last - 1])}, default settings, generated by
\`make-plan-reference.js\` from \`js/plan.js\` (the indicator's tested reference). Times are candle
open times in UTC.

- All four filters agreed on **${short + long}** candles (${((100 * (short + long)) / n).toFixed(0)}%): ${short} short, ${long} long.
- Momentum was choppy on ${chop} candles.
- Full signals: **${rows.filter((x) => x.includes('**signal**')).length}**.

## Every trigger pattern that formed while the filters agreed

| Candle (UTC) | Pattern | Close | Stop | First target | Result |
|---|---|---|---|---|---|
${rows.join('\n') || '| - | none | | | | |'}
`;
const out = path.join(path.dirname(file), path.basename(file, '.json') + '-plan.md');
fs.writeFileSync(out, md);
console.log(md);
